export const tForm = (lang, key) =>
  copy[lang]?.[key] || copy.en[key] || key;

export const bilingualLabel = (key) => ({
  en: tForm("en", key),
  gu: tForm("gu", key),
});

export const bilingualOptions = (values, prefix) =>
  (values || []).map((value) => {
    const key = prefix ? `${prefix}.${value}` : value;
    return {
      id: value,
      value,
      name: bilingualLabel(key),
      label: tForm("en", key),
    };
  });

export const labeledOptions = (lang, prefix, values) =>
  (values || []).map((value) => ({
    value,
    label: tForm(lang, `${prefix}.${value}`),
  }));
